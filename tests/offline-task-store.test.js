import test from 'node:test';
import assert from 'node:assert/strict';
import 'fake-indexeddb/auto';
import {unzipSync,strFromU8,zipSync,strToU8} from 'fflate';
import {project} from '../src/domain.js';
import {createOfflineHandoff,importEditableWork,inspectEditablePackageSource,inspectOfflinePackage,importEditableWorkPackage} from '../src/offline-creation.js';
import {createOfflineTaskStore} from '../src/offline-task-store.js';

test('O-01/O-03: original task survives reopen, is account-scoped, and binds imports',async()=>{
  const asset={id:'task-asset',title:'真实贴纸',kind:'sticker',role:'focal',physicalWidthMM:40,physicalHeightMM:50,supply:{quantity:1}};
  const handoff=await createOfflineHandoff({project:project('任务'),assets:[asset],aliases:{m1:asset.id},settings:{includeThumbnails:false}});
  const files=unzipSync(new Uint8Array(await handoff.blob.arrayBuffer()));
  assert.equal(inspectOfflinePackage(new Uint8Array(await handoff.blob.arrayBuffer())).source.bundleId,handoff.source.bundleId);
  const response=JSON.parse(strFromU8(files['examples/project.shiyeproject.json']));
  const name='offline-task-test-'+crypto.randomUUID(),store=createOfflineTaskStore({name});
  await store.save('account-a',handoff.source);
  const reopened=createOfflineTaskStore({name}),trusted=await reopened.load('account-a',handoff.source.bundleId);
  assert.deepEqual(trusted,handoff.source);
  assert.equal(await reopened.load('account-b',handoff.source.bundleId),null);
  assert.throws(()=>importEditableWork(JSON.stringify(response),[asset]),/原始任务/);
  assert.equal(importEditableWork(JSON.stringify(response),[asset],{trustedSource:trusted}).drafts[0].items[0].assetID,asset.id);
  const zip=zipSync({'project.shiyeproject.json':strToU8(JSON.stringify(response))});
  assert.equal(inspectEditablePackageSource(zip).bundleId,handoff.source.bundleId);
  assert.equal(importEditableWorkPackage(zip,[asset],{trustedSource:trusted}).drafts[0].items.length,1);
  response.source.processing='自由拆解';
  assert.throws(()=>importEditableWork(JSON.stringify(response),[asset],{trustedSource:trusted}),/原始任务不一致/);
  delete response.source.taskBinding;
  assert.throws(()=>importEditableWork(JSON.stringify(response),[asset],{trustedSource:trusted}),/原始任务不一致/);
  response.source.taskBinding='local-v1';
  await assert.rejects(reopened.save('account-a',response.source),/已有不同/);
  response.source={...trusted};
  response.source=Object.fromEntries(Object.entries(response.source).reverse());
  assert.equal(importEditableWork(JSON.stringify(response),[asset],{trustedSource:trusted}).drafts[0].items.length,1);
  const tamperedContext=JSON.parse(strFromU8(files['task/context.json']));
  tamperedContext.materials[0].assetID='other-asset';
  assert.throws(()=>inspectOfflinePackage(zipSync({'task/context.json':strToU8(JSON.stringify(tamperedContext))})),/素材映射不一致/);
});
