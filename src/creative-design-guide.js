export const purposeMethod=name=>purposeMethods[name]||'按本次明确用途建立阅读顺序与具体内容，不照搬空模板。';
export function creativeDesignGuide(source,{hasImages=true,hasPresets=false}={}){
  const styles=(source.styles||[]).map((name,i)=>`${i+1}. ${name}：${styleMethods[name]||'按本次主题与可见素材决定配色、主次和留白。'}`).join('\n');
  const purposes=(source.purposes||[]).map((name,i)=>`${i+1}. ${name}：${purposeMethod(name)}`).join('\n');
  const text=source.textMode==='none'?'本次不生成文字；用可编辑图形建立视觉层级。':source.textMode==='requested'?'没有明确文字要求时不主动配文；若有要求，全部以可编辑文本实现。':'需要真正有内容的标题、图注与正文/条目；段落尽量合并为可编辑的多行文本框，不逐字拆层。';
  return `拾页创作方法指南｜辅助构思，不是固定模板\n\n`+
    `一、先理解素材，再构图\n${hasImages?'逐件查看 materials/ 透明图片及 context.json 中的名称、尺寸、类型、角色、库存；区分轮廓、色彩、方向、印刷文字与空白处。':'本包不带素材图片，只能依据 context.json 给出的事实创作；未知外观不猜。'}\n选择一个能讲清主题的主件，其他素材承担补充、引导或留白的作用。不要求用尽全部素材，但必用清单和指定用法必须满足。同一批素材在不同用途下应得到不同的信息顺序。\n\n`+
    `二、所选风格如何落地\n${styles||'按素材决定视觉语言。'}\n多风格时第一项是主语，后续只提取一两种可兼容特征，避免把互相冲突的颜色/纹理全堆进去。风格指排版与色彩方法，不是购买或凭空造出新纸片。\n\n`+
    `三、所选用途决定内容\n${purposes||purposeMethods.日常记录}\n多用途时先满足第一项的核心信息，再用第二项补充一个小区块；例如「日常记录＋清单」仍是故事页面，清单只辅助回顾。\n\n`+
    `四、版式推演\n先在脑中比较至少两种构图：主图＋旁注、错层叙事、分栏收藏、留白封面、时间/路线、任务清单等；选择与本次素材形状及用途最匹配的一种。让主图、标题、正文、图注之间有清楚的视线顺序与大小差。正文需可读，元素不能跑出纸张、盖住文字或把所有对象集中于中心。双页应考虑跨页节奏与装订中线，不让关键字跨中缝。数字线、荧光笔、色块、图框只在能组织信息时添加，并写入可编辑 graphics/tools，不只画进预览图。真实日记页常同时用剪贴、图注、多行记录和可编辑小图形形成内容密度：除主题封面或明确要求极简/无文字外，不能只放一两件素材加一个标题就交付。素材不足时先增加原创但不杜撰经历的多行文字、图注、数字线条或底色，调整信息层次；不要创造不存在的实体贴纸。\n${hasPresets?'references/ 是四张根据本次风格与用途生成、抽象自公开真实手帐的匿名区域示意；先读 references/GUIDE.txt。它们不是你的私人作品，也不是最终页面模板。':'不附加图片样例时，也可使用 composition-ideas.json 的文字构图思路。'}\n\n`+
    `五、文字与真实性\n${text} 主标题、正文、注释要有层级；必要时用多行、行间距与宽度控制阅读，不靠逐字拆框。可写原创通用主题句或对可见图片的客观说明；不得杜撰用户的日期、地点、人物经历、引语来源或照片细节。\n\n`+
    `六、同一篮素材，按用途改写构图\n下面是方法示范而非本次素材清单：假设手里有一张图像、一张小纸片和一截胶带。做「日常记录」，图像靠近可编辑观察段落，小纸片承托一段短注，胶带连起两组内容；做「图文收藏」，依主题分组、主图配图注，纸片可以成为分类标题；做「清单计划」，纸片承载几条可勾选记录，图像退为视觉锚点；做「主题封面」，图像成为主角，纸片和胶带只用于突出短标题。四种用途使用相同材料，但信息层级、文字量和留白不同。实际素材不存在或用途不合时，不能照此凭空添加。\n\n`+
    `七、从简单到复杂的四级试排\n简洁版：一件主件、标题、至少一处多行正文与图注；非封面页不能像空白占位稿。均衡版：主件、次要材料与两个相互关联的可编辑图文组建立主次。丰富版：分栏、局部叠层与多个内容组形成节奏，保持边距和段间空隙，不把素材平均摊开。实验版：可用对角、局部出血、负空间或不规则错层，但不能让任何实物尺寸、正文可读性或页面边界失控。四级没有质量高低之分；依据实际材料数量、形状和用途选择，不为追求复杂而塞满纸张。\n\n`+
    `八、细节制作的可执行办法\n先决定纸色与底纹是否需要；底纸是整页背景，真实纸片仍按实体素材计数。再定一个主视觉与一个阅读入口：主视觉可以是照片、插画、文字标题或真实票据，不必永远在中心。使标题、正文、图注的字号形成清楚梯度；细分栏时先保证文字宽度与完整行高，避免把段落压在贴纸下面。可编辑直线用于划分或引导，荧光色带用于少量文字强调，装饰图形只重复一两种形状以形成统一感。贴纸透明边缘应保持透明，不能因预览背景自动添加白方块。需要叠压时只遮无关空白，不遮照片主体、印刷信息或文字。颜色先从可见素材提取主色、辅助色、强调色；没有图片时只用元数据明确给出的颜色，不臆造图案。\n\n`+
    `九、阅读与真实世界复核\n缩到整页预览时应立即看到主题焦点；放大后每段文字仍完整、能沿动线读完。检查：有没有空相框或占位词？有没有自称真实经历却无证据？双页中线是否切断重要对象？每件素材的尺寸和可用数量是否吻合？裁剪是否真能从一件纸片得到，剩余料是否与其他裁片不重叠？如果其中一项不合格，先调整排版/配文/加工，不靠改动实物尺寸蒙混。模型可自由创造可编辑文字、数字笔触与图形，但无法让现实中不存在的照片、贴纸或纸张自动出现。\n\n`+
    `十、物理与交付自检\n实体纸、照片、贴纸按真实毫米尺寸使用，不放大、不凭空复制、不超库存。只用合同支持的直裁、裁片、胶带截段；裁下的非重叠余料可继续用，胶带长度可连续但宽度不可变。预览图中出现的每件真实素材、每条线、每个色块和每段文字，都必须在返回数据中有相应可编辑图层。导入对象的 ID、纸张规格与 source 必须匹配 ZIP；以 contract.json 和 example-response.shiyeproject.json 为字段准绳，先内部核对合同再交付。`;
}
