  旅途记录:'有票据、地图或照片时可按「出发—路途—回望」编排；无地点或日期证据时写关于旅途的通用观察，不杜撰真实行程。',
  图文收藏:'将素材按形状、颜色或主题分组，每组有短标题、可编辑图注和明确的阅读顺序；不建无内容的空相框。',
