const purposeMethods={
  日常记录:'用可见细节引出标题，让连贯的多行观察与照片/贴纸彼此靠近；没有经历证据不写「今天我去了」。',
  旅途记录:'有票据、地图或照片时可按「出发—路途—回望」编排；无地点或日期证据时写关于旅途的通用观察，不杜撰真实行程。',
  图文收藏:'将素材按形状、颜色或主题分组，每组有短标题、可编辑图注和明确的阅读顺序；不建无内容的空相框。',
  清单计划:'列出具体可编辑条目、勾选标记和可读的分组；未给具体计划时写可通用的主题清单，不假装已完成事件。',
  影像故事:'从主图的可见事实开始，辅图或文字回应同一主题；用大小差和图注串起起承转合，不把图片机械排成等大方阵。',
  主题封面:'突出主题短标题与一件主视觉；留白可多，副题可少，但要有真实的焦点与明确风格，不硬塞长正文。'
};
export const purposeMethod=name=>purposeMethods[name]||'按本次明确用途建立阅读顺序与具体内容，不照搬空模板。';
export function creativeDesignGuide(source,{hasImages=true,hasPresets=false,referenceCases}={}){
  const styles=(source.styles||[]).map((name,i)=>`${i+1}. ${name}：${styleMethods[name]||'按本次主题与可见素材决定配色、主次和留白。'}`).join('\n');
  const purposes=(source.purposes||[]).map((name,i)=>`${i+1}. ${name}：${purposeMethod(name)}`).join('\n');
  const text=source.textMode==='none'?'本次不生成文字；可用可编辑图形建立视觉层级。':source.textMode==='requested'?'没有明确文字要求时不主动配文；若有要求，全部以可编辑文本实现。':'根据主题选择标题、图注、正文或条目，避免空洞占位；需要较长段落时尽量合并为可编辑的多行文本框，不逐字拆层。';
  const cases=referenceCases||selectJournalReferenceCases({styles:source.styles,purposes:source.purposes});
  return `拾页创作方法指南｜辅助构思，不是固定模板\n\n`+
    `一、先理解素材，再构图\n${hasImages?'逐件查看 materials/ 透明图片及 context.json 中的名称、尺寸、类型、角色；区分轮廓、色彩、方向、印刷文字与空白处。':'本包不带素材图片，只能依据 context.json 给出的事实创作；未知外观不猜。'}\n让适合的素材围绕主题形成主次和呼应，不把其余素材机械地排在边上。必用清单逐件落实；其余候选尽量使用，但不必勉强塞入。同一批素材在不同用途下应得到不同的信息顺序。\n${creativePageBrief({styles:source.styles,purposes:source.purposes,textMode:source.textMode,contentPolicy:source.contentPolicy,userText:source.userText,theme:source.intent,pageMode:source.mode})}\n\n`+
    `二、所选风格如何落地\n${styles||'按素材决定视觉语言。'}\n多风格时第一项是主语，后续只提取一两种可兼容特征，避免把互相冲突的颜色/纹理全堆进去。风格指排版与色彩方法，不是购买或凭空造出新纸片。\n\n`+
    `三、所选用途决定内容\n${purposes||purposeMethods.日常记录}\n多用途时先满足第一项的核心信息，再用第二项补充一个小区块；例如「日常记录＋清单」仍是故事页面，清单只辅助回顾。正文写主题本身，不写为什么这样摆、如何配色或选了什么素材；案例图里的文字也不可抄入本次作品。\n\n`+
    `四、版式推演\n让主图、标题、正文、图注形成清楚的视线顺序与大小差；有意错层或留白也可以成立。双页考虑跨页节奏与装订中线。数字线、荧光笔、色块、图框只在能组织信息时添加，并写入可编辑 graphics/tools，不只画进预览图。素材少时可用原创但不杜撰经历的文字、图注或数字图形补充；若安静的留白更贴合主题，就保留留白。不要创造不存在的实体贴纸。\n${hasPresets?'先读 abstract-templates.json：其中是按本次风格、用途与素材选出的少数来源模板；每条有模板原图编号，只有能够确认真实成品时才有 exampleSourceNumbers。没有对应成品也可以使用模板，不要猜配。source-image-audit.json 区分案例图、模板图及同图并列。references/ 是风格相近的原创重构案例，不是用户原图、可用素材或固定坐标模板。':'未附图片样例时可用 composition-ideas.json 的一般构图方法，但不能声称它们是用户原图中的抽象模板。'}\n\n`+
    `五、文字、图形与真实性\n${text} 主标题、正文、注释要有层级；必要时用多行、行间距与宽度控制阅读，不靠逐字拆框。${creativeLayeringGuide}可写原创通用主题句或对可见图片的客观说明；不得杜撰用户的日期、地点、人物经历、引语来源或照片细节。${hasPresets?`\n${journalReferenceGuide(cases)}`:''}\n\n`+
    `六、同一篮素材，按用途改写构图\n下面是方法示范而非本次素材清单：假设手里有一张图像、一张小纸片和一截胶带。做「日常记录」，图像靠近可编辑观察段落，小纸片承托一段短注，胶带连起两组内容；做「图文收藏」，依主题分组、主图配图注，纸片可以成为分类标题；做「清单计划」，纸片承载几条可勾选记录，图像退为视觉锚点；做「主题封面」，图像成为主角，纸片和胶带只用于突出短标题。四种用途使用相同材料，但信息层级、文字量和留白不同。实际素材不存在或用途不合时，不能照此凭空添加。\n\n`+
    `七、从来源模板改造\n${hasPresets?'有确认成品的模板可以连同成品关系借鉴；没有确认成品的模板独立借鉴，不把相似风格案例伪称其对应原作。几条候选模板不必全用。':'本包未提供来源模板，不要把一般版式建议伪称为用户图片中的模板。'}依据实际材料数量、形状和用途决定使用其中哪种图文关系；不复制案例文字、具体照片或固定坐标，也不为追求复杂而塞满纸张。\n\n`+
    `八、细节制作的可执行办法\n先决定纸色与底纹是否需要；底纸是整页背景，真实纸片仍按实体素材计数。再定一个主视觉与一个阅读入口：主视觉可以是照片、插画、文字标题或真实票据，不必永远在中心。使标题、正文、图注的字号形成清楚梯度；细分栏时先保证文字宽度与完整行高，避免把段落压在贴纸下面。可编辑直线用于划分或引导，荧光色带用于少量文字强调，装饰图形只重复一两种形状以形成统一感。贴纸透明边缘应保持透明，不能因预览背景自动添加白方块。需要叠压时只遮无关空白，不遮照片主体、印刷信息或文字。颜色先从可见素材提取主色、辅助色、强调色；没有图片时只用元数据明确给出的颜色，不臆造图案。\n\n`+
    `九、阅读与真实世界复核\n缩到整页预览时应立即看到主题焦点；放大后每段文字仍完整、能沿动线读完。检查：有没有空相框或占位词？有没有自称真实经历却无证据？双页中线是否切断重要对象？每件素材的尺寸和可用数量是否吻合？裁剪是否真能从一件纸片得到，剩余料是否与其他裁片不重叠？如果其中一项不合格，先调整排版/配文/加工，不靠改动实物尺寸蒙混。模型可自由创造可编辑文字、数字笔触与图形，但无法让现实中不存在的照片、贴纸或纸张自动出现。\n\n`+
    `十、物理与交付自检\n实体纸、照片、贴纸按真实毫米尺寸使用，不放大、不凭空复制；普通素材每方案只取用一份源素材。只使用合同明确支持的取材、参数化边缘、布尔裁切、开窗、胶带和组合工艺；裁下的非重叠余料可继续用，胶带长度可连续但宽度不可变。素材和图形可以伸出纸边形成出血，最终页面只显示纸内部分；这不是尺寸或来源区域违规，重要内容应留在可见区域。预览图中出现的每件真实素材、每条线、每个色块和每段文字，都必须在返回数据中有相应可编辑图层。导入对象的 ID、纸张规格与 source 必须匹配 ZIP；以 contract.json 和 example-response.shiyeproject.json 为字段准绳，先内部核对合同再交付。`;
}
