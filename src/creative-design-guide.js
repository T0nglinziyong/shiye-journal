  影像故事:'从主图的可见事实开始，辅图或文字回应同一主题；用大小差和图注串起起承转合，不把图片机械排成等大方阵。',
  主题封面:'突出主题短标题与一件主视觉；留白可多，副题可少，但要有真实的焦点与明确风格，不硬塞长正文。'
