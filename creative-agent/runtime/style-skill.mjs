先用少量决定面积的大件试摆，再安排中小件和文字。主纸层叠式可让一件成为重心，另一件从横纵两方向深入错入，露出宽窄不同且有作用的纹样或撕口；人物、标题或照片可跨接接缝。上下分区式让不同段落或图组各有落点，用重复色、字群、裁片或连接物呼应。图文混合式先给文字找实际可读的背景，再让图像从字群旁穿过，让文字成为视觉形状的一部分。左右双簇、规整分栏中的越界元素、同级素材的重复阵列也可依内容采用。同类纸张、卡片或图像成对时，可让两件分别落在斜线两端，形成明显的横向和纵向错距；三件时可沿两段斜线形成折线与转折。各落点可一大一小或相近，可深入叠压，也可分置并让背景承字。第三片纸、人物、字群和点缀能连接不同对象，让路线从一簇自然通向另一簇。对象可正放或斜放，角度按轮廓、图案方向和人物动作选择。双页各有主次，可一页集中、一页上下展开或高低错位，整体仍有色彩或内容回声。缩看每页第一、第二落点以及最终重心，按画面调整各簇的面积、距离和色重；中尺度内容也能帮助分置的主卡与正文形成关系。

