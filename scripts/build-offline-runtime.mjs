import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';

const root=resolve(import.meta.dirname,'..'),output=resolve(root,'src/generated/offline-validate-source.js');
const browser=await build({entryPoints:[resolve(root,'src/offline-browser-entry.mjs')],bundle:true,platform:'browser',format:'iife',globalName:'ShiyeScene',target:'es2022',write:false,minify:true,legalComments:'none'});
await mkdir(resolve(root,'src/generated'),{recursive:true});
const browserModule=`// Generated by scripts/build-offline-runtime.mjs; do not edit by hand.\nexport const offlineBrowserSource=${JSON.stringify(browser.outputFiles[0].text)};\n`;
const browserOutput=resolve(root,'src/generated/offline-browser-source.js');
let oldBrowser='';try{oldBrowser=await readFile(browserOutput,'utf8');}catch{}
if(oldBrowser!==browserModule)await writeFile(browserOutput,browserModule);
const glyph=await build({entryPoints:[resolve(root,'src/offline-glyph-entry.mjs')],bundle:true,platform:'node',format:'cjs',target:'node20',write:false,minify:true,legalComments:'none'});
const glyphOutput=resolve(root,'src/generated/offline-glyph-source.js');
const glyphModule=`// Generated by scripts/build-offline-runtime.mjs; do not edit by hand.\nexport const offlineGlyphSource=${JSON.stringify(glyph.outputFiles[0].text)};\n`;
let oldGlyph='';try{oldGlyph=await readFile(glyphOutput,'utf8');}catch{}
if(oldGlyph!==glyphModule)await writeFile(glyphOutput,glyphModule);
const result=await build({entryPoints:[resolve(root,'src/offline-runtime-entry.mjs')],bundle:true,platform:'node',format:'cjs',target:'node20',write:false,minify:true,legalComments:'none',plugins:[{name:'no-self-embed',setup(builder){
  builder.onResolve({filter:/generated\/offline-validate-source\.js$/},()=>({path:'generated-validator',namespace:'self-stub'}));
  builder.onLoad({filter:/.*/,namespace:'self-stub'},()=>({contents:'export const offlineValidateSource="";',loader:'js'}));
}}]});
const source=result.outputFiles[0].text;
await mkdir(resolve(root,'src/generated'),{recursive:true});
const module=`// Generated by scripts/build-offline-runtime.mjs; do not edit by hand.\nexport const offlineValidateSource=${JSON.stringify(source)};\n`;
let previous='';try{previous=await readFile(output,'utf8');}catch{}
if(previous!==module)await writeFile(output,module);
process.stdout.write(`Offline validator bundled: ${Buffer.byteLength(source)} bytes\n`);
